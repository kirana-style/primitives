/**
 * Writes `@kirana-ui/vocabulary` from the part definitions the core runs on, so the published
 * vocabulary cannot drift from what the parts write:
 *
 *   src/vocabulary.json   the data, for any tool
 *   src/index.ts          the same, typed
 *   src/keys.ts           each state as a selector, by component and part (`Dialog.Popup.open`),
 *                         and the pairs that never hold together: the shape a styling system
 *                         takes its condition keys in
 *   REFERENCE.md          every part's attributes and variables, to read
 *
 *   bun scripts/vocabulary.ts            writes them
 *   bun scripts/vocabulary.ts --check    fails when one is out of date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

import type { PartDefinition } from "../packages/core/src/part.ts"
import { vocabulary } from "../packages/core/src/vocabulary.ts"

const OUT = join(import.meta.dirname, "../packages/vocabulary")
const HEADER =
  "// @generated by scripts/vocabulary.ts from the core's part definitions. Do not edit."

const pascal = (name: string) => name[0]!.toUpperCase() + name.slice(1)
const selector = (attribute: string, value?: string) =>
  value === undefined ? `[${attribute}]` : `[${attribute}="${value}"]`

interface State {
  attribute: string
  description: string
  /** For a state the attribute marks by being present. */
  selector?: string
  /** For a state the attribute carries as a value: each value's selector. */
  values?: Record<string, string>
}

interface Part {
  description: string
  states: Record<string, State>
  /** Groups of state names that never hold together on the element. */
  exclusive: string[][]
  variables: Record<string, string>
}

export function build() {
  const components: Record<string, { parts: Record<string, Part> }> = {}
  for (const [component, parts] of Object.entries(vocabulary)) {
    components[component] = { parts: {} }
    for (const [name, part] of Object.entries<PartDefinition>(parts)) {
      const states: Record<string, State> = {}
      for (const [key, each] of Object.entries(part.states ?? {})) {
        states[key] = each.values
          ? {
              attribute: each.attribute,
              description: each.description,
              values: Object.fromEntries(
                each.values.map((value) => [value, selector(each.attribute, value)])
              ),
            }
          : {
              attribute: each.attribute,
              description: each.description,
              selector: selector(each.attribute),
            }
      }
      components[component]!.parts[name] = {
        description: part.description,
        states,
        exclusive: (part.exclusive ?? []).map((group) => [...group]),
        variables: { ...part.variables },
      }
    }
  }
  return {
    // The format's version: a consumer checks it before it reads.
    version: 1,
    // Vocabularies whose attribute names these are too: a style written for one holds for both.
    sharesNamesWith: ["base-ui"],
    components,
  }
}

type Data = ReturnType<typeof build>

function keys(data: Data): string {
  const pairs = new Map<string, string[]>()
  const lines: string[] = [
    HEADER,
    "",
    "/**",
    " * States the parts set one at a time, as selectors: a styling system that checks for two",
    " * conditions on one property can be told these never meet.",
    " */",
  ]
  const body: string[] = []
  for (const [component, { parts }] of Object.entries(data.components)) {
    body.push("", `export const ${pascal(component)} = {`)
    for (const [name, part] of Object.entries(parts)) {
      body.push(`  /** ${part.description} */`, `  ${pascal(name)}: {`)
      for (const [key, each] of Object.entries(part.states)) {
        body.push(`    /** ${each.description} */`)
        if (each.values) {
          body.push(`    ${key}: {`)
          for (const [value, text] of Object.entries(each.values)) {
            body.push(`      ${value}: ${JSON.stringify(text)},`)
          }
          body.push("    },")
        } else {
          body.push(`    ${key}: ${JSON.stringify(each.selector)},`)
        }
      }
      body.push("  },")
      for (const group of part.exclusive) {
        const selectors = group.map((key) => part.states[key]!.selector!)
        pairs.set(selectors.join(" "), selectors)
      }
      for (const each of Object.values(part.states)) {
        if (!each.values) continue
        const selectors = Object.values(each.values)
        pairs.set(selectors.join(" "), selectors)
      }
    }
    body.push("} as const")
  }
  lines.push("export const exclusive: string[][] = [")
  for (const group of pairs.values()) lines.push(`  ${JSON.stringify(group)},`)
  lines.push("]")
  return [...lines, ...body, ""].join("\n")
}

function reference(data: Data): string {
  const lines = [
    "<!-- Generated by scripts/vocabulary.ts from the core's part definitions. Do not edit. -->",
    "",
    "# The vocabulary",
    "",
    "Every part's states and CSS variables. A state is an attribute on the part's element: style",
    "it with an attribute selector (`.panel[data-open]`). A variable is a custom property on the",
    "element: read it with `var()`. The names follow Base UI's.",
  ]
  for (const [component, { parts }] of Object.entries(data.components)) {
    lines.push("", `## ${pascal(component)}`)
    for (const [name, part] of Object.entries(parts)) {
      lines.push("", `### ${pascal(component)}.${pascal(name)}`, "", part.description)
      const states = Object.values(part.states)
      if (states.length > 0) {
        lines.push("", "| Attribute | When |", "| --- | --- |")
        for (const each of states) {
          const values = each.values ? ` (${Object.keys(each.values).join(", ")})` : ""
          lines.push(`| \`${each.attribute}\`${values} | ${each.description} |`)
        }
      }
      const variables = Object.entries(part.variables)
      if (variables.length > 0) {
        lines.push("", "| Variable | Holds |", "| --- | --- |")
        for (const [variable, description] of variables) {
          lines.push(`| \`${variable}\` | ${description} |`)
        }
      }
    }
  }
  return `${lines.join("\n")}\n`
}

export function files(): Record<string, string> {
  const data = build()
  const json = `${JSON.stringify(data, null, 2)}\n`
  return {
    "src/vocabulary.json": json,
    "src/index.ts": `${HEADER}\n\nexport const vocabulary = ${json.trimEnd()} as const\n\nexport type Vocabulary = typeof vocabulary\n`,
    "src/keys.ts": keys(data),
    "REFERENCE.md": reference(data),
  }
}

if (import.meta.main) {
  const check = process.argv.includes("--check")
  let stale = 0
  for (const [path, content] of Object.entries(files())) {
    const target = join(OUT, path)
    const current = existsSync(target) ? readFileSync(target, "utf8") : undefined
    if (current === content) continue
    if (check) {
      stale++
      console.error(`out of date: packages/vocabulary/${path}`)
    } else {
      writeFileSync(target, content)
      console.log(`wrote packages/vocabulary/${path}`)
    }
  }
  if (stale > 0) {
    console.error("run `vp run vocabulary` and commit the result")
    process.exit(1)
  }
}
